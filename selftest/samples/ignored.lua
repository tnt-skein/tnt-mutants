--- Образец самопроверки: правила исключения.
---
--- Самопроверка пишет к нему свой список правил: живое глушит одну строку,
--- широкое — две одинаковые, мёртвое не совпадает ни с одной, а ещё одно
--- не разбирается вовсе. Прогон обязан отказать на мёртвом и неразборчивом,
--- назвав их строки в списке, и назвать широкое вслух, не отказывая.
---
--- Все мутанты вне заглушённых строк погибают: отказ на этом образце
--- обязан идти от правил, а не от выживших.

local Module = {}

--- Строка под живым правилом: мутантов на ней нет.
---@return integer
function Module.first()
    return 1
end

--- Шаг вперёд. Объявление шага глушит широкое правило.
---@param value number
---@return number
function Module.forward(value)
    local step = 2
    return value + step
end

--- Шаг назад. Объявление шага — вторая строка широкого правила.
---@param value number
---@return number
function Module.back(value)
    local step = 2
    return value - step
end

return Module

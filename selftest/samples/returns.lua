--- Образец самопроверки: возвраты.
---
--- Глушитель в `rules/lua.rules` обязан пропускать логический возврат
--- и возврат имени — это развилки — и глушить только возврат таблицы
--- модуля и пустой возврат. Глушитель любого возврата одного слова
--- показывал бы сто процентов по непроверенным веткам.
---
--- Проверка образца нарочно не смотрит ответ `flag`: оба его мутанта
--- обязаны выжить и попасть в отчёт. Ответ `pick` она смотрит,
--- и его мутант обязан погибнуть.

local Module = {}

--- Логический ответ: его подмену прогон обязан показать выжившей.
---@return boolean
function Module.flag()
    return true
end

--- Возврат имени: его подмену проверка ловит.
---@param value any
---@return any
function Module.pick(value)
    return value
end

--- Пустой возврат: мутировать в нём нечего.
---@return nil
function Module.nothing()
    return nil
end

return Module

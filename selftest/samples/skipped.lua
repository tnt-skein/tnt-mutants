--- Образец самопроверки: строки, пропущенные генератором.
---
--- Одиночное число внутри многострочного вызова генератор проверяет наспех:
--- подменяет строку мусором, файл компилируется — и строка объявлена
--- мёртвой, мутантов на ней нет. Прогон обязан назвать такую строку вслух.

local Module = {}

--- Отказ с уровнем на отдельной строке: уровень генератор не мутирует.
---@param reason string
function Module.fail(reason)
    error(
        ('образец самопроверки отказал: %s — уровень стоит отдельной строкой'):format(
            reason
        ),
        0
    )
end

--- Рядом обычный код: без него мутантов не было бы вовсе.
---@param value number
---@return boolean
function Module.is_even(value)
    return value % 2 == 0
end

return Module
